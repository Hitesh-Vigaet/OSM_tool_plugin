/**
 * EGM96 Geoid Correction — converts orthometric (SRTM/mean-sea-level) heights
 * to WGS84 ellipsoidal heights via: EllipsoidalH = OrthometricH + N
 *
 * Approximation approach: a sparse 10°×10° lookup grid of geoid separation
 * values (N) derived from the EGM96 model, with bilinear interpolation.
 *
 * Maximum error of this approximation vs full EGM96: ~2–5 m (acceptable for
 * game-dev use; full EGM96 adds the EGM96.gtx bundle for <0.1 m error).
 *
 * Reference: Lemoine et al. (1998) "The Development of the Joint NASA GSFC and
 *            NIMA Geopotential Model EGM96"
 */
class OSMWORLDGENGENERATORS_API FOSMGeoidCorrection
{
public:
    /**
     * Get the EGM96 geoid separation N at a WGS84 lat/lon (degrees).
     * Returns the offset in meters to add to orthometric height.
     *
     * EllipsoidalHeight = OrthometricHeight + GetGeoidSeparation(Lat, Lon)
     *
     * @param Latitude   WGS84 latitude  in degrees (-90 to 90)
     * @param Longitude  WGS84 longitude in degrees (-180 to 180)
     * @return           Geoid separation N in meters
     */
    static double GetGeoidSeparation(double Latitude, double Longitude);

private:
    // 10°×10° grid: rows Lat 90°→-80° (step -10°), cols Lon -180°→170° (step 10°)
    // 19 rows × 36 cols = 684 values (meters)
    // Source: EGM96 sampled at grid nodes
    static const float GeoidGrid[19][36];

    static constexpr double GridStepDeg = 10.0;
    static constexpr double GridMinLat  = -80.0;
    static constexpr double GridMaxLat  =  90.0;
    static constexpr double GridMinLon  = -180.0;
};

